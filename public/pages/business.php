	var chk_agreement = '1';
	
	//리스트로드
	function loadList() {
		jq('#area_list_tmp').load('../lib/talk/talk_list.html','talk_id=sssssss&tpage=',function(){
			jq('#loading_container').remove();
		});
	}

	var tmr = null; 
	var pre_length = 140;
	var max_length = 140;
	function startLen(id) { 
		var id = id;
		var el = jq('#'+id+'_length'); 
		var remain = jq('#'+id).val().length; 
		if ( pre_length != remain ) { 
			el.text(remain); 
			if ( parseInt(remain) > parseInt(max_length) ) { 
				el.css('color','#dd0000'); 
			}
			else {
				el.css('color',''); 
			}
			pre_length=remain;
		} 
		tmr = window.setTimeout('startLen("'+id+'")',100);    // 0.1초에 한 번씩 반복 
	}

	function stopLen() {
		clearTimeout(tmr);
		tmr = null; 
	}

	function execTalk(mode) {
		if (mode.match('add|modify')) {
			if (jq("#"+mode+"_content").val().length > max_length) {
				alert(xpack[2680]);
				return false;
			}
		}

		if(mode=='add' && chk_agreement) {
			var frm = document.forms['frmTalk'];
			//개인정보동의여부체크
			if (!frm.chk_agreement.checked) {
				alert(xpack[2628]);
				return false;
			}
		}

		//필드체크
		var valid = validateField('frmTalk');
		if (valid) {
			jq('#mode').val(mode);
			Ext.get("frmTalk").dom.submit();
		}
		else return false;
	}

	function callbackSubmit(key) {
		jq.ajax({
			asyn: ( vasyn == 1 ) ? true : false,
			url: '/lib/talk/talk.process.php',
			dataType: 'json',
			type: 'POST',
			data: "key=" + key,
			success: function(rtn){
				alert(rtn.msg);
				if (rtn.success) {
					if(jq("input[name='add_name']").length > 0) jq("input[name='add_name']").val('');
					if(jq("input[name='add_phone']").length > 0) jq("input[name='add_phone']").val('');
					if(jq("input[name='add_mobile']").length > 0) jq("input[name='add_mobile']").val('');
					if(jq("input[name='add_addr']").length > 0) jq("input[name='add_addr']").val('');
					if(jq("#chk_agreement").is(':checked')) jq("#chk_agreement").attr('checked',false);
					jq('#add_content').val('');
					jq("input[name='add_password']").val('');
					startLen('add_content');
					loadList();
				}
			}
		});
	}

	function toggleArea(obj)
	{
		if (obj==undefined) {
			var obj = "area_add";
		}
		jq("#area_add").hide();
		jq("#area_delete").hide();
		jq("#area_modify").hide();
		jq("#" + obj).show();
	}

